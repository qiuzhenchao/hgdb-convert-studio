-- 01-create-test-user.sql（JDBC 版：每条语句后跟 / 分隔）
-- 以 DBA 身份执行（system），密码 Test#1234；无密码有效期。

CREATE PROFILE test_profile LIMIT PASSWORD_LIFE_TIME UNLIMITED;
/

CREATE USER test IDENTIFIED BY "Test#1234" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA UNLIMITED ON USERS PROFILE test_profile;
/

ALTER USER test IDENTIFIED BY "Test#1234" PROFILE test_profile ACCOUNT UNLOCK;
/

ALTER USER test QUOTA UNLIMITED ON USERS;
/

GRANT CONNECT TO test;
/

GRANT RESOURCE TO test;
/

GRANT CREATE VIEW TO test;
/

GRANT CREATE PROCEDURE TO test;
/

GRANT CREATE TRIGGER TO test;
/

GRANT CREATE SEQUENCE TO test;
/

GRANT CREATE TYPE TO test;
/

GRANT UNLIMITED TABLESPACE TO test;
/

GRANT CREATE SYNONYM TO test;
/

GRANT CREATE JOB TO test;
